(( EUID == 0 )) && { echo >&2 'This script should not be run as root!'; exit 1; }

# -------------------------------------------------------------------------------------------------------------------- #
# CONFIGURATION
# -------------------------------------------------------------------------------------------------------------------- #

# Sources.
SRC_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" &> /dev/null && pwd -P )"; readonly SRC_DIR
SRC_NAME="$( basename "$( readlink -f "${BASH_SOURCE[0]}" )" )"; readonly SRC_NAME
# shellcheck source=/dev/null
. "${SRC_DIR}/${SRC_NAME%.*}.conf"

# Parameters.
DATA="${DATA:?}"; readonly DATA
HOST="${HOST:?}"; readonly HOST
PORT="${PORT:?}"; readonly PORT

# -------------------------------------------------------------------------------------------------------------------- #
# -----------------------------------------------------< SCRIPT >----------------------------------------------------- #
# -------------------------------------------------------------------------------------------------------------------- #

function init() {
  cd "${HOME}" || exit; [[ ! -d "${DATA}" ]] && exit 1
  DATA_DIR="${DATA}" "${HOME}/.venv/bin/open-webui" serve --host "${HOST}" --port "${PORT}"
}

function main() {
  init
}; main "$@"
